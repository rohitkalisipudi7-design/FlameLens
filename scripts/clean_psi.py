"""Cleans and standardizes NASA PSI experimental tables into structured datasets by physical family.

Usage: .venv/Scripts/python scripts/clean_psi.py
Inputs: data/psi/*/Experimental table/*.csv, investigation.json, psi_index.csv, data/ntrs/catalog.csv
Outputs (data/clean/):
  droplets.csv, gas_flames.csv, solids.csv   combustion test runs, one row per run
  aerosols.csv                                 smoke aging and particle tracking (SAME, SAME-R, DAFT)
  sessions.csv                                 operational daily logs (ACME BRE/CLD/E-FIELD/s-Flame, SLICE)
  experiments_all.csv                          unified schema with direct NASA PSI links and DOIs
  campaigns.csv, publications.csv              profiles of each flight investigation and related papers
  skipped_rows.csv                             non-test header/summary lines from raw tables
  data_dictionary.md, qc_report.md             data dictionary and data cleaning anomaly audit

Zero silent corrections: every normalized value logs an explicit 'column:reason' flag in qc_flags,
and every row retains strict traceability (source_file, source_line).
"""
import os, sys
from collections import Counter

import pandas as pd

from cleaning import droplets, gas, other, solids
from cleaning.common import BASE, SKIPPED
from cleaning.schema import COLUMNS, FLAG_REASONS
from cleaning.sources import campaigns, publications
from cleaning.validate import validate

OUT = os.path.join(BASE, "data", "clean")
FIRST = ["uid", "accession", "campaign", "family", "test_id", "date"]
LAST = ["n_flags", "qc_flags", "excluded", "exclude_reason", "source_file", "source_line"]
COMMON = ["uid", "accession", "campaign", "family", "test_id", "date", "fuel_or_material", "pressure_atm", "x_o2",
          "flow_cm_s", "ignited", "extinguished", "end_mode", "burn_time_s", "n_flags", "qc_flags", "excluded",
          "psi_url", "doi_url"]


def frame(records):
    df = pd.DataFrame(records)
    df = validate(df)
    mid = [c for c in df.columns if c not in FIRST + LAST]
    return df[FIRST + mid + LAST]


def common_view(df, camp):
    v = pd.DataFrame(index=df.index)
    for c in COMMON:
        v[c] = df[c] if c in df else None
    v["fuel_or_material"] = df["fuel"] if "fuel" in df else df.get("material")
    if "air_velocity_cm_s" in df:
        v["flow_cm_s"] = v["flow_cm_s"].fillna(df["air_velocity_cm_s"]) if "flow_cm_s" in df else df["air_velocity_cm_s"]
    links = camp.set_index("accession")
    v["psi_url"] = df["accession"].map(links["psi_url"])
    v["doi_url"] = df["accession"].map(links["doi_url"])
    return v[COMMON]


def write(df, name):
    df.to_csv(os.path.join(OUT, name), index=False, encoding="utf-8")


def dictionary(tables):
    lines = ["# Data Dictionary — data/clean",
             "", "Generated by `scripts/clean_psi.py`. Physical units in SI or standard combustion research notation; "
             "mole fractions bounded in [0, 1].", ""]
    for name, df in tables.items():
        lines += [f"## {name}", "", "| Column | Unit | Description |", "|---|---|---|"]
        for c in df.columns:
            unit, desc = COLUMNS[c]
            lines.append(f"| `{c}` | {unit} | {desc} |")
        lines.append("")
    lines += ["## Quality Control Flags (`qc_flags`)", "",
              "Format: `column:reason`, separated by `; `. A quality flag does not invalidate the row; it denotes that "
              "the value was normalized, imputed, or flagged as anomalous. `excluded = true` explicitly flags duplicate rows "
              "that should be omitted from model training.", "", "| Flag Reason | Description |", "|---|---|"]
    lines += [f"| `{k}` | {v} |" for k, v in FLAG_REASONS.items()]
    return "\n".join(lines) + "\n"


# Interpretaciones que el script deja marcadas pero sin resolver. Se mantienen tal cual mientras nadie
# las confirme con los papers; si alguna resulta relevante para el modelo, decidir aquí y en el adaptador.
OPEN_QUESTIONS = [
    ("SIBAL Specimen Thickness in SAFFIRE", "`thickness_mm:inconsistente_entre_campanas`",
     "SAFFIRE-I and III report 0.37 and 0.33 **cm**; SAFFIRE-II records `037 mm` (0.37 **mm**). A 10x unit discrepancy "
     "exists between flight logs. Both values are retained with an explicit warning flag."),
    ("Inferred Specimen Material in BASS / BASS-II", "`material:inferido`",
     "Descriptions such as `2 cm sphere` or `1/4\" black rod` omit material nomenclature; PMMA was inferred as the only "
     "material tested in these geometries across both campaigns."),
    ("Unspecified Diluent in SPICE Fuel Blends", "`x_fuel:diluyente_no_especificado`",
     "`75% Propylene` and `50% Propylene` omit diluent identification (N2 vs propane). The mole fraction is retained with "
     "fuel normalized to propylene and flagged for review."),
]


def report(tables, camp, skipped):
    lines = ["# Scientific Quality Report — NASA PSI Data Cleaning", "",
             "Generated by `scripts/clean_psi.py`.", "",
             "## Documented Scientific Discrepancies", "",
             "Historical discrepancies identified in raw NASA PSI experimental matrices. "
             "All rows are preserved with explicit quality control flags for model auditability.", "",
             "| Topic | Flag | Context |", "|---|---|---|"]
    lines += [f"| {t} | {f} | {d} |" for t, f, d in OPEN_QUESTIONS]
    lines += ["", "## Standardized Records by Campaign", "",
             "| Campaign | Family | Table Kind | Rows | Flagged | Excluded |", "|---|---|---|---:|---:|---:|"]
    for _, c in camp.sort_values(["family", "campaign"], na_position="last").iterrows():
        family = c.family if isinstance(c.family, str) else "—"
        lines.append(f"| {c.campaign} ({c.accession}) | {family} | {c.table_kind} | {c.n_rows} | "
                     f"{c.n_flagged} | {c.n_excluded} |")
    for name, df in tables.items():
        flags = Counter(f for s in df["qc_flags"].dropna() for f in s.split("; "))
        nulls = df.drop(columns=FIRST + LAST, errors="ignore").isna().mean().sort_values(ascending=False)
        lines += ["", f"## {name} ({len(df)} rows)", "", "Most frequent flags:", ""]
        lines += [f"- `{k}` × {v}" for k, v in flags.most_common(15)] or ["- (none)"]
        lines += ["", "Columns with highest missing rates:", ""]
        lines += [f"- `{k}`: {v:.0%}" for k, v in nulls.items() if v > 0][:12] or ["- (none)"]
    lines += ["", "## Discarded Lines from Original Tables", "", "| Source File | Line | Reason |", "|---|---:|---|"]
    lines += [f"| {s['source_file']} | {s['source_line']} | {s['reason']} |" for s in skipped]
    return "\n".join(lines) + "\n"


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    os.makedirs(OUT, exist_ok=True)
    tables = {
        "droplets.csv": frame(droplets.build()),
        "gas_flames.csv": frame(gas.build()),
        "solids.csv": frame(solids.build()),
        "aerosols.csv": frame(other.build_aerosols()),
        "sessions.csv": frame(other.build_sessions()),
    }
    stats, names = {}, {}
    for df in tables.values():
        for acc, g in df.groupby("accession"):
            stats[acc] = {"family": g["family"].iloc[0], "rows": len(g), "flagged": int((g["n_flags"] > 0).sum()),
                          "excluded": int(g["excluded"].sum())}
            names[acc] = g["campaign"].iloc[0]
    camp = pd.DataFrame(campaigns(stats, names))
    pubs = pd.DataFrame(publications())
    skipped = pd.DataFrame(SKIPPED)
    tests = [n for n in tables if n != "sessions.csv"]
    allx = pd.concat([common_view(tables[n], camp) for n in tests], ignore_index=True)

    for name, df in tables.items():
        write(df, name)
    write(allx, "experiments_all.csv")
    write(camp, "campaigns.csv")
    write(pubs, "publications.csv")
    write(skipped, "skipped_rows.csv")

    documented = {**tables, "experiments_all.csv": allx, "campaigns.csv": camp, "publications.csv": pubs,
                  "skipped_rows.csv": skipped}
    missing = sorted({c for df in documented.values() for c in df.columns if c not in COLUMNS})
    if missing:
        raise SystemExit(f"Columnas sin documentar en cleaning/schema.py: {missing}")
    unknown = sorted({f.split(":", 1)[1] for df in tables.values() for s in df["qc_flags"].dropna()
                      for f in s.split("; ")} - set(FLAG_REASONS))
    if unknown:
        raise SystemExit(f"Motivos de qc_flags sin documentar en cleaning/schema.py: {unknown}")
    open(os.path.join(OUT, "data_dictionary.md"), "w", encoding="utf-8").write(dictionary(documented))
    open(os.path.join(OUT, "qc_report.md"), "w", encoding="utf-8").write(report(tables, camp, SKIPPED))

    for name, df in tables.items():
        print(f"{name:16} {len(df):5} rows  {int((df['n_flags'] > 0).sum()):4} flagged  "
              f"{int(df['excluded'].sum()):3} excluded")
    print(f"experiments_all  {len(allx):5} rows | campaigns {len(camp)} | publications {len(pubs)} "
          f"({pubs['ntrs_url'].notna().sum()} linked to NTRS) | skipped lines {len(skipped)}")


if __name__ == "__main__":
    main()
